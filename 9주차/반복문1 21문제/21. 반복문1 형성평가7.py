while True :
    alp = input()
    if alp == "A" :
        print("ADD")
        continue
    elif alp == "B" :
        print("BACk")
        continue
    elif alp == "C" :
        print("COPY")
        continue
    elif alp == "D" :
        print("DELETE")
        continue
    elif alp == "E" :
        print("EXIT")
        break
    else :
        print("NONE")
        continue
